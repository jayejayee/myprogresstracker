create table if not exists public.reminders (
  id bigint generated by default as identity primary key,
  userprofile text not null default auth.uid()::text,
  entity_type text not null check (entity_type in ('task', 'project')),
  entity_id bigint not null,
  entity_title text not null,
  next_at timestamptz not null,
  timezone text not null default 'UTC',
  repeat_rule text not null default 'once'
    check (repeat_rule in ('once', 'daily', 'weekly', 'monthly')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  unique (userprofile, entity_type, entity_id)
);

create index if not exists reminders_due_idx
  on public.reminders (next_at)
  where enabled;

create table if not exists public.push_subscriptions (
  endpoint text primary key,
  userprofile text not null default auth.uid()::text,
  subscription jsonb not null,
  created_at timestamptz not null default now()
);

alter table public.reminders enable row level security;
alter table public.push_subscriptions enable row level security;

drop policy if exists "Users can manage their own reminders"
  on public.reminders;
create policy "Users can manage their own reminders"
  on public.reminders
  for all
  to authenticated
  using ((select auth.uid())::text = userprofile)
  with check (
    (select auth.uid())::text = userprofile
    and (
      (entity_type = 'task' and exists (
        select 1
        from public.todolist as owned_task
        where owned_task.id = entity_id
          and owned_task.userprofile = (select auth.uid())::text
      ))
      or (entity_type = 'project' and exists (
        select 1
        from public.projects as owned_project
        where owned_project.id = entity_id
          and owned_project.userprofile = (select auth.uid())::text
      ))
    )
  );

drop policy if exists "Users can manage their own push subscriptions"
  on public.push_subscriptions;
create policy "Users can manage their own push subscriptions"
  on public.push_subscriptions
  for all
  to authenticated
  using ((select auth.uid())::text = userprofile)
  with check ((select auth.uid())::text = userprofile);

grant select, insert, update, delete on public.reminders to authenticated;
grant select, insert, update, delete on public.push_subscriptions to authenticated;

do $$
declare
  reminders_sequence regclass := pg_get_serial_sequence('public.reminders', 'id');
begin
  if reminders_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to authenticated',
      reminders_sequence
    );
  end if;
end
$$;