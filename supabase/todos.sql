create table if not exists public.todolist (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  todo text not null check (char_length(trim(todo)) between 1 and 200),
  todoby date,
  completedstatus boolean not null default false,
  userprofile text not null default auth.uid()::text
);

alter table public.todolist
  add column if not exists userprofile text;

alter table public.todolist
  alter column userprofile set default auth.uid()::text;

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 120),
  due_date date not null,
  userprofile text not null default auth.uid()::text,
  created_at timestamptz not null default now()
);

alter table public.todolist
  add column if not exists projectid bigint references public.projects (id) on delete set null;

alter table public.projects enable row level security;

drop policy if exists "Users can manage their own projects" on public.projects;

create policy "Users can manage their own projects"
  on public.projects
  for all
  to authenticated
  using ((select auth.uid())::text = userprofile)
  with check ((select auth.uid())::text = userprofile);

alter table public.todolist
  drop constraint if exists todolist_userprofile_key;

alter table public.todolist enable row level security;

drop policy if exists "Users can manage their own todos" on public.todolist;

create policy "Users can manage their own todos"
  on public.todolist
  for all
  to authenticated
  using ((select auth.uid())::text = userprofile)
  with check (
    (select auth.uid())::text = userprofile
    and (
      projectid is null
      or exists (
        select 1
        from public.projects as owned_project
        where owned_project.id = todolist.projectid
          and owned_project.userprofile = (select auth.uid())::text
      )
    )
  );

grant select, insert, update, delete on table public.todolist to authenticated;
grant select, insert, update, delete on table public.projects to authenticated;

do $$
declare
  todo_id_sequence regclass := pg_get_serial_sequence('public.todolist', 'id');
  project_id_sequence regclass := pg_get_serial_sequence('public.projects', 'id');
begin
  if todo_id_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to authenticated',
      todo_id_sequence
    );
  end if;
  if project_id_sequence is not null then
    execute format(
      'grant usage, select on sequence %s to authenticated',
      project_id_sequence
    );
  end if;
end
$$;